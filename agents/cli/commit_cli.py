"""
CLI entry point for ``agent-commit``.

Commits files using the agent's git author identity.  The commit
message is generated by sending the staged diff to the LLM backend.

Usage
-----
    agent-commit --tracked              Commit tracked modified files
    agent-commit --all                  Commit all changed files (including untracked)
    agent-commit file1.py file2.py      Commit specific files
    agent-commit -m claude-fable-5 --all  Use a specific model (auto-detects online/local)
    agent-commit -o --all               Use online model for commit message
"""

import argparse
import os
import platform
import sys

from ..agents import (
    _extract_commit_message,
    read_configuration,
    resolve_backend_target,
)
from ..backends import create_backend
from ..config import load_agent_config
from ..ui import confirm_unresolved_model
from ..git_utils import (
    is_git_repo,
    get_all_changed_files,
    get_staged_files,
    get_tracked_modified_files,
    git_add_and_commit,
    _run_git,
)


_BACKTICK = "`" * 5


def _get_agent_author(model: str) -> tuple[str, str]:
    """Use the resolved model identity, exactly as agent auto-commits do."""
    return model, f"agent@{platform.node()}"


COMMIT_SYSTEM_PROMPT = (
    "You are a git commit message generator. You receive a unified diff "
    "and must produce a single, concise commit message on one line. "
    "Wrap the commit message in five backticks like in the following "
    f"example.\n{_BACKTICK}\nCommit message here\n{_BACKTICK}"
)


def _generate_commit_message(
    diff: str,
    files: list[str],
    *,
    online: bool = False,
    model: str | None = None,
    agent_config: str = "basic_agent.yaml",
) -> tuple[str, str]:
    """Return the LLM's commit message and the resolved model identifier.

    Use the same configured defaults and routing as the agent CLI. Failures
    propagate to the caller: never replace an LLM response with a fabricated
    filename-based message.
    """
    config = read_configuration(agent_config)
    agent_cfg = load_agent_config()

    local_host = os.environ.get("LOCAL_LLM_HOST", "localhost")
    try:
        local_port = int(os.environ.get("LOCAL_LLM_PORT", "8000"))
    except (TypeError, ValueError):
        local_port = 8000
    provider, model, base_url = resolve_backend_target(
        confirm_local_fallback=confirm_unresolved_model,
        model_name=model,
        cli_online=online,
        local_model=(None if (model is not None or online)
                     else os.environ.get("LOCAL_MODEL")),
        local_host=local_host,
        local_port=local_port,
        config_provider=agent_cfg.get("provider") or config.get("provider"),
        config_model=agent_cfg.get("model"),
        # Preserve an explicit empty URL from the default-model tool.
        config_base_url=agent_cfg.get("base_url", config.get("base_url")),
    )
    client = create_backend(provider, model=model, base_url=base_url)

    # Truncate diff to avoid overwhelming the context window
    max_diff = 300_000
    if len(diff) > max_diff:
        diff = (
            diff[:max_diff]
            + f"\n\n... [diff truncated, {len(diff) - max_diff:,} more chars] ..."
        )

    file_list = ", ".join(os.path.basename(f) for f in files)
    fence = "`" * 3
    user_message = f"Files changed: {file_list}\n\n{fence}\n{diff}\n{fence}"

    context = [
        {"role": "user", "content": [{"type": "text", "text": user_message}]}
    ]

    response = client.generate_response(COMMIT_SYSTEM_PROMPT, context)
    message = _extract_commit_message(response)
    if not message:
        raise ValueError("The model returned no usable commit message.")
    return message, model


def main():
    """Parse arguments and perform the commit."""
    parser = argparse.ArgumentParser(
        prog="agent-commit",
        description="Generate a commit message with the LLM and commit as that model.",
    )

    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--tracked",
        action="store_true",
        help="Commit all tracked files with changes (modified, deleted, renamed).",
    )
    mode.add_argument(
        "--all",
        action="store_true",
        help="Commit all changed files including untracked ones.",
    )
    parser.add_argument(
        "-m", "--model",
        type=str,
        default=None,
        help="Model used to generate the message and as the Git author. Online models are "
             "auto-detected (no -o needed). Unknown model names "
             "require confirmation before local fallback; -o/--online disables fallback.",
    )
    parser.add_argument(
        "-o", "--online",
        action="store_true",
        help="Use the online model provider for the commit message "
             "(disables local fallback and ignores inherited local settings).",
    )
    parser.add_argument(
        "files",
        nargs="*",
        help="Specific files to commit (used when --tracked and --all are omitted).",
    )

    args = parser.parse_args()

    if not is_git_repo("."):
        print("Error: not a git repository.", file=sys.stderr)
        sys.exit(1)

    pre_staged = set(get_staged_files("."))

    if args.tracked:
        files = sorted(
            set(get_tracked_modified_files(".")) | pre_staged
        )
        if not files:
            print("No tracked files with changes to commit.")
            sys.exit(0)
    elif args.all:
        files = get_all_changed_files(".")
        if not files:
            print("No files to commit.")
            sys.exit(0)
    else:
        if not args.files:
            parser.error("Provide --tracked, --all, or specific file paths.")
        files = sorted(set(args.files))

    # Refuse to sweep unrelated pre-staged changes into the commit.
    # (--all intentionally includes everything already staged.)
    if not args.all:
        outside = sorted(pre_staged - set(files))
        if outside:
            print(
                "Error: the index contains pre-staged files outside the "
                "requested commit set:\n  " + "\n  ".join(outside)
                + "\nUnstage them first, or use --all to commit everything.",
                file=sys.stderr,
            )
            sys.exit(1)

    # Stage files first so we can get the diff
    # ('--' guards against filenames that start with a dash)
    _, stderr, rc = _run_git("add", "--", *files, cwd=".")
    if rc != 0:
        print(f"git add failed: {stderr}", file=sys.stderr)
        sys.exit(1)

    # Get the staged diff for the LLM (restricted to the target files
    # so the message isn't polluted by unrelated staged changes)
    diff, stderr, rc = _run_git("diff", "--cached", "--", *files, cwd=".")
    if rc != 0:
        print(f"git diff failed: {stderr}", file=sys.stderr)
        sys.exit(1)
    if not diff:
        print("No staged changes to commit.")
        return

    # Generate commit message from the diff
    try:
        message, resolved_model = _generate_commit_message(
            diff, files, online=args.online, model=args.model
        )
    except Exception as exc:
        print(
            f"Commit message generation failed: {exc}\n"
            "No commit was created; changes remain staged.",
            file=sys.stderr,
        )
        sys.exit(1)
    author_name, author_email = _get_agent_author(resolved_model)

    # Commit (files are already staged)
    ok, err = git_add_and_commit(
        message,
        author_name=author_name,
        author_email=author_email,
        files=files,
    )

    if ok:
        print(f"Committed {len(files)} file(s) as {author_name} <{author_email}>:")
        for f in files:
            print(f"  {f}")
        print(f'  "{message}"')
    else:
        print(f"Commit failed: {err}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
